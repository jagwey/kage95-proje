using Kage95.Api.Services;

namespace Kage95.Tests;

public class PasswordAndPointsTests
{
    [Fact]
    public async Task PasswordService_HashAndVerify_WorksCorrectly()
    {
        var svc = new PasswordService();
        var hash = await svc.HashPasswordAsync("Kage95StrongPass!");

        Assert.Contains(':', hash);
        Assert.True(await svc.VerifyPasswordAsync("Kage95StrongPass!", hash));
        Assert.False(await svc.VerifyPasswordAsync("WrongPassword123", hash));
        Assert.False(await svc.VerifyPasswordAsync("Kage95StrongPass!", "invalid-hash"));
    }

    [Fact]
    public async Task PasswordService_VerifiesExistingNodeJsScryptHash()
    {
        // Generated by Node.js server/auth.mjs: crypto.scryptSync('Kage95NodeVector!', salt, 32, { N: 131072, r: 8, p: 1 })
        const string nodeHash = "0123456789abcdef0123456789abcdef:a069f194c87526aef575f072e6649466ea10f7a5a97d0a982f6768444f616cd1";
        var svc = new PasswordService();
        Assert.True(await svc.VerifyPasswordAsync("Kage95NodeVector!", nodeHash));
        Assert.False(await svc.VerifyPasswordAsync("WrongPass!", nodeHash));
    }

    [Theory]
    [InlineData(0, 1, "Çırak")]
    [InlineData(99, 1, "Çırak")]
    [InlineData(100, 2, "Çırak")]
    [InlineData(300, 3, "Genç Gölge")]
    [InlineData(1500, 6, "Gölge")]
    [InlineData(6600, 12, "Usta")]
    [InlineData(30000, 25, "Efsane")]
    public void PointsService_LevelAndRankCurve_MatchesKage95Rules(int totalPoints, int expectedLevel, string expectedTitle)
    {
        Assert.Equal(expectedLevel, PointsService.ComputeLevel(totalPoints));
        Assert.Equal(expectedTitle, PointsService.ComputeTitle(totalPoints));
    }

    [Fact]
    public void PointsService_NextTitle_ReturnsNullAtTopRank()
    {
        var (next, remaining) = PointsService.ComputeNextTitle(0);
        Assert.Equal("Genç Gölge", next);
        Assert.Equal(300, remaining);

        var (topNext, topRem) = PointsService.ComputeNextTitle(50000);
        Assert.Null(topNext);
        Assert.Equal(0, topRem);
    }
}
